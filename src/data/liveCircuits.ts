import type { Destination, Trip, TripNode } from '@/types'

const TODAY = '2026-09-27'

function place(city: string, state: string, id = city.toLowerCase().replace(/\s+/g, '-')): Destination {
  return { id, city, state, label: city }
}

function stamp(nodes: TripNode[]): TripNode[] {
  let activeSet = false
  return nodes.map((node) => {
    if (node.status === 'alternative') return node
    if (node.date < TODAY) return { ...node, status: 'visited' }
    if (node.date === TODAY && !activeSet) {
      activeSet = true
      return { ...node, status: 'active' }
    }
    return { ...node, status: 'upcoming' }
  })
}

function n(
  id: string,
  day: number,
  date: string,
  title: string,
  city: string,
  time: string,
  category: TripNode['category'],
  cost: number,
  notes: string,
): TripNode {
  return { id, day, date, title, city, time, category, status: 'upcoming', cost, notes }
}

function trip(partial: Omit<Trip, 'nodes' | 'alternatives' | 'feasibility' | 'spent'> & { nodes: TripNode[]; feasibility?: number }): Trip {
  const nodes = stamp(partial.nodes)
  const spent = nodes.filter((node) => node.status === 'visited' || node.status === 'active').reduce((sum, node) => sum + node.cost, 0)
  return {
    ...partial,
    feasibility: partial.feasibility ?? 88,
    alternatives: [],
    nodes,
    spent,
  }
}

